using System;
using System.Collections.Generic;
namespace VehicleInheritance
{
    // Базовый класс
    public class Автомобиль
    {
        // Поля (свойства)
        public string Марка { get; set; }
        public string Госномер { get; set; }
        // Конструктор
        public Автомобиль(string марка, string госномер)
        {
            Марка = марка;
            Госномер = госномер;
        }
        // Виртуальный метод (может быть переопределен)
        public virtual void Показать()
        {
            Console.WriteLine($"Автомобиль: марка - {Марка}, номер - {Госномер}");
        }
    }
    // Производный класс: Легковой автомобиль
    public class ЛегковойАвтомобиль : Автомобиль
    {
        // Дополнительное свойство
        public int ЧислоМест { get; set; }
        // Конструктор
        public ЛегковойАвтомобиль(string марка, string госномер, int числоМест)
            : base(марка, госномер)
        {
            ЧислоМест = числоМест;
        }
        // Переопределение метода
        public override void Показать()
        {
            Console.WriteLine($"Легковой автомобиль: марка - {Марка}, номер - {Госномер}, число пассажирских мест - {ЧислоМест}");
        }
    }
    // Производный класс: Грузовой автомобиль
    public class ГрузовойАвтомобиль : Автомобиль
    {
        // Дополнительное свойство
        public double Грузоподъемность { get; set; }
        // Конструктор
        public ГрузовойАвтомобиль(string марка, string госномер, double грузоподъемность)
            : base(марка, госномер)
        {
            Грузоподъемность = грузоподъемность;
        }
        // Переопределение метода
        public override void Показать()
        {
            Console.WriteLine($"Грузовой автомобиль: марка - {Марка}, номер - {Госномер}, грузоподъемность - {Грузоподъемность} тонн");
        }
    }
    class Program
    {
        static void Main(string[] args)
        {
            // Создание объектов
            Автомобиль автомобиль1 = new Автомобиль("Lada", "А123ВС");
            ЛегковойАвтомобиль автомобиль2 = new ЛегковойАвтомобиль("Toyota", "В456ОР", 5);
            ГрузовойАвтомобиль автомобиль3 = new ГрузовойАвтомобиль("КАМАЗ", "С789ТУ", 15.5);
            ЛегковойАвтомобиль автомобиль4 = new ЛегковойАвтомобиль("BMW", "Х321КМ", 4);
            ГрузовойАвтомобиль автомобиль5 = new ГрузовойАвтомобиль("MAN", "У654НЕ", 20.0);
            // Сохранение в коллекцию (список)
            List<Автомобиль> автомобили = new List<Автомобиль>
            {
                автомобиль1,
                автомобиль2,
                автомобиль3,
                автомобиль4,
                автомобиль5
            };
            // Вызов переопределенных методов в цикле
            Console.WriteLine("Информация об автомобилях:");
            Console.WriteLine("==========================");
            foreach (var авто in автомобили)
            {
                авто.Показать(); // Будет вызван соответствующий переопределенный метод
            }
            Console.ReadKey();
        }
    }
}